"""Лёгкое правило выбора режима ответа без дополнительных LLM вызовов.

Python 3.9+. Пытается распознавать намерение, а не наличие слова 'маршрут'.
"""
import re

ROUTE_PLANNING = re.compile(
    r"(?:\b(?:составь|построй|спланируй|разработай|предложи|проложи|создай)\b.{0,65}\bмаршрут\b)"
    r"|(?:\bмаршрут\b.{0,65}\b(?:на|за)\s+\d+\s*(?:день|дня|дней)\b)"
    r"|(?:\b(?:план|программа)\s+(?:поездки|путешествия|посещения|прогулки)\b)"
    r"|(?:\b(?:itinerary|plan a route|build a route)\b)", re.IGNORECASE | re.DOTALL
)
ROUTE_EDIT = re.compile(
    r"\b(?:измени|переделай|исправь|скорректируй|обнови|переставь|замени|убери|исключи|удали|добавь)\b"
    r".{0,85}\b(?:маршрут|остановк\w*|перв\w*\s+д(?:ень|ня)|втор\w*\s+д(?:ень|ня)|музе\w*)\b"
    r"|\b(?:убери|исключи|замени|добавь)\b.{0,85}\b(?:из|в)\s+(?:перв\w*|втор\w*)\s+д(?:ень|ня)\b",
    re.IGNORECASE | re.DOTALL
)


def classify_request(question: str) -> str:
    """Возвращает 'route', 'route_edit' или 'qa'.

    'route_edit' пока обрабатывается обычным RAG с историей; отдельного
    детерминированного редактирования существующего маршрута ещё нет.
    """
    text = ' '.join(question.split())
    if ROUTE_EDIT.search(text):
        return 'route_edit'
    if ROUTE_PLANNING.search(text):
        return 'route'
    return 'qa'
